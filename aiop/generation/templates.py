"""Deterministic, knowledge-driven TileLang A5 kernel templates.

Every family renders a self-contained module:

    def build(): -> @T.prim_func

The planner decides tiling from hardware budgets; templates only materialize
the already-validated plan, which keeps generated code reviewable and removes
the most common class of LLM API hallucinations.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ..runtime.hardware import Plan
from ..specs import DTYPE_BYTES, TaskSpec

HEADER = '''"""A5 TileLang operator generated by aiop.

op: {name}
family: {family}
plan: {plan_json}
source: deterministic template {template} (knowledge/04, knowledge/06)
"""

# fmt: off
import tilelang
import tilelang.ascend.language as T

PASS_CONFIGS = {pass_configs}


'''


def _t(name: str, tensor, dtype: str | None = None) -> str:
    dt = dtype or tensor.dtype
    shape = tuple(tensor.shape)
    shape_s = f"({shape[0]},)" if len(shape) == 1 else str(shape)
    return f"{name}: T.Tensor({shape_s}, {json.dumps(dt)})"


def _flat_t(name: str, tensor, dtype: str | None = None) -> str:
    dt = dtype or tensor.dtype
    return f"{name}: T.Tensor(({tensor.numel},), {json.dumps(dt)})"


def _fp32(value: str) -> str:
    return f"T.cast({value}, T.float32)"


def _to(dtype: str, value: str) -> str:
    if dtype == "float32":
        return value
    return f"T.cast({value}, {json.dumps(dtype)})"


def _unary_expr(name: str, src: str, dtype: str, dst_dtype: str) -> str:
    transcendental = name in {"exp", "sigmoid", "tanh", "rsqrt", "sqrt", "log"}
    if name == "cast":
        return _to(dst_dtype, _fp32(src) if dtype != "float32" else src)
    if transcendental:
        inner = {
            "exp": "T.exp({})",
            "sigmoid": "T.sigmoid({})",
            "tanh": "T.tanh({})",
            "rsqrt": "T.rsqrt({})",
            "sqrt": "T.sqrt({})",
            "log": "T.log({})",
        }[name].format(_fp32(src) if dtype != "float32" else src)
        return _to(dtype, inner) if dtype != "float32" else inner
    if name == "relu":
        if dtype != "float32":
            return _to(dtype, f"T.max({_fp32(src)}, T.float32(0))")
        return f"T.max({src}, T.float32(0))"
    if name == "abs":
        # tirx.fabs is not lowered by the A5 codegen; fp32 max(x, -x) is
        # equivalent and avoids ambiguous bf16/fp16 max overloads.
        return _to(dtype, f"T.max({_fp32(src)}, -({_fp32(src)}))")
    if name == "neg":
        return f"-({src})"
    raise ValueError(f"unsupported unary op {name}")


def _binary_expr(name: str, a: str, b: str, dtype: str = "float32") -> str:
    if name in ("maximum", "minimum"):
        fn = "T.max" if name == "maximum" else "T.min"
        if dtype != "float32":
            return _to(dtype, f"{fn}({_fp32(a)}, {_fp32(b)})")
        return f"{fn}({a}, {b})"
    return {
        "add": f"({a} + {b})",
        "sub": f"({a} - {b})",
        "mul": f"({a} * {b})",
        "div": f"({a} / {b})",
    }[name]


def _elementwise(spec: TaskSpec, plan: Plan) -> str:
    dtype = spec.inputs[0].dtype
    out_dtype = spec.output.dtype
    total = spec.output.numel
    blocks, tile, threads = plan.blocks, plan.tile, plan.threads
    if plan.variant == "simt_ub_staged":
        bufs = []
        copies_in = []
        for idx, tensor in enumerate(spec.inputs):
            name = chr(ord("a") + idx)
            bufs.append(f"            {name} = T.alloc_shared((TILE,), {json.dumps(tensor.dtype)})")
            copies_in.append(f"                T.copy({tensor.name}[begin : begin + TILE], {name})")
        bufs.append(f"            c = T.alloc_shared((TILE,), {json.dumps(out_dtype)})")
        versions = ", ".join(
            f"{chr(ord('a') + i)}: NUM_STAGES" for i in range(len(spec.inputs))
        ) + ", c: NUM_STAGES"
        if spec.family == "elementwise_binary":
            expr = _binary_expr(spec.name, "a[i]", "b[i]", dtype)
        else:
            expr = _unary_expr(spec.name, "a[i]", dtype, out_dtype)
        body = "\n".join(bufs)
        copies = "\n".join(copies_in)
        source = f'''def build():
    N = {total}
    TILE = {tile}
    BLOCKS = {blocks}
    THREADS = {threads}
    NUM_STAGES = {plan.num_stages}
    ITERS = {plan.iterations}

    @T.prim_func
    def main({", ".join(_flat_t(t.name, t) for t in spec.inputs)}, {_flat_t(spec.output.name, spec.output)}):
        with T.Kernel(BLOCKS) as bx:
{body}
            T.annotate_buffer_versions({{{versions}}})
            for step in T.Pipelined(ITERS, num_stages=NUM_STAGES):
                begin = (step * BLOCKS + bx) * TILE
{copies}
                with T.SimtVF(threads=THREADS):
                    for i in T.Parallel(TILE):
                        c[i] = {expr}
                T.copy(c, {spec.output.name}[begin : begin + TILE])

    return main
'''
    else:
        if spec.family == "elementwise_binary":
            expr = _binary_expr(spec.name, f"{spec.inputs[0].name}[idx]", f"{spec.inputs[1].name}[idx]", dtype)
        else:
            expr = _unary_expr(
                spec.name, f"{spec.inputs[0].name}[idx]", dtype, out_dtype
            )
        source = f'''def build():
    N = {total}
    TILE = {tile}
    BLOCKS = {blocks}
    THREADS = {threads}
    ITERS = {plan.iterations}

    @T.prim_func
    def main({", ".join(_flat_t(t.name, t) for t in spec.inputs)}, {_flat_t(spec.output.name, spec.output)}):
        with T.Kernel(BLOCKS) as bx:
            for step in T.serial(ITERS):
                begin = (step * BLOCKS + bx) * TILE
                with T.SimtVF(threads=THREADS):
                    for i in T.Parallel(TILE):
                        idx = begin + i
                        if idx < N:
                            {spec.output.name}[idx] = {expr}

    return main
'''
    return source


def _row_common(spec: TaskSpec, plan: Plan) -> str:
    return f'''def build():
    BATCH = {spec.input.numel // spec.input.shape[-1]}
    D = {spec.input.shape[-1]}
    TILE = {plan.tile_extent}
    ROWS = {plan.rows}
    CORES = {plan.blocks}
    THREADS = {plan.threads}
    ITERS = {plan.iterations}
    EPS = {float(spec.attrs.get("eps", 1e-6))}
'''


def _row_reduce(spec: TaskSpec, plan: Plan) -> str:
    op = spec.reduce_op or "sum"
    fill = {"sum": "T.float32(0)", "max": "T.float32(-3.0e38)", "min": "T.float32(3.0e38)"}[op]
    src_dtype = spec.input.dtype
    out_dtype = spec.output.dtype
    post = " / T.float32(D)" if spec.name == "reduce_mean" else ""
    shape_in = tuple(spec.input.shape)
    shape_out = tuple(spec.output.shape)
    return _row_common(spec, plan) + f'''
    @T.prim_func
    def main(X: T.Tensor({shape_in}, {json.dumps(src_dtype)}), Y: T.Tensor({shape_out}, {json.dumps(out_dtype)})):
        with T.Kernel(CORES) as core:
            for t in T.Pipelined(ITERS, num_stages=2):
                base_row = (t * CORES + core) * ROWS
                with T.SimtVF(threads=THREADS):
                    x = T.alloc_fragment((ROWS, TILE), T.float32)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        row = T.min(base_row + r, BATCH - 1)
                        x[r, i] = T.if_then_else(i < D, T.cast(X[row, i], T.float32), {fill})
                    acc = T.alloc_reducer((ROWS,), T.float32, op="{op}")
                    T.reducer_init(acc)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        T.reducer_update(acc[r], x[r, i])
                    res = T.alloc_fragment((ROWS,), T.float32)
                    T.finalize_reducer(acc, res)
                    for r in T.Parallel(ROWS):
                        if base_row + r < BATCH:
                            Y[base_row + r] = {"T.cast(res[r]" + post + f", {json.dumps(out_dtype)})" if out_dtype != "float32" else "res[r]" + post}

    return main
'''


def _softmax(spec: TaskSpec, plan: Plan) -> str:
    dtype = spec.input.dtype
    shape = tuple(spec.input.shape)
    return _row_common(spec, plan) + f'''
    @T.prim_func
    def main(X: T.Tensor({shape}, {json.dumps(dtype)}), Y: T.Tensor({shape}, {json.dumps(dtype)})):
        with T.Kernel(CORES) as core:
            for t in T.Pipelined(ITERS, num_stages=2):
                base_row = (t * CORES + core) * ROWS
                with T.SimtVF(threads=THREADS):
                    x = T.alloc_fragment((ROWS, TILE), T.float32)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        row = T.min(base_row + r, BATCH - 1)
                        x[r, i] = T.if_then_else(i < D, T.cast(X[row, i], T.float32), T.float32(-3.0e38))
                    rmax = T.alloc_reducer((ROWS,), T.float32, op="max")
                    T.reducer_init(rmax)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        T.reducer_update(rmax[r], x[r, i])
                    mx = T.alloc_fragment((ROWS,), T.float32)
                    T.finalize_reducer(rmax, mx)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        x[r, i] = T.if_then_else(i < D, T.exp(x[r, i] - mx[r]), T.float32(0))
                    rsum = T.alloc_reducer((ROWS,), T.float32, op="sum")
                    T.reducer_init(rsum)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        T.reducer_update(rsum[r], x[r, i])
                    sm = T.alloc_fragment((ROWS,), T.float32)
                    T.finalize_reducer(rsum, sm)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        if base_row + r < BATCH:
                            if i < D:
                                Y[base_row + r, i] = {"T.cast(x[r, i] / sm[r], " + json.dumps(dtype) + ")" if dtype != "float32" else "x[r, i] / sm[r]"}

    return main
'''


def _norm(spec: TaskSpec, plan: Plan) -> str:
    dtype = spec.input.dtype
    shape = tuple(spec.input.shape)
    is_layer = spec.family == "layernorm"
    eps = spec.attrs.get("eps", 1e-6)
    w_dtype = spec.inputs[1].dtype
    w_shape = tuple(spec.inputs[1].shape)
    bias_decl = ""
    bias_load = ""
    w_name = spec.inputs[1].name
    w_decl = f"            w_ub = T.alloc_shared({w_shape}, {json.dumps(w_dtype)})"
    w_load = f"            T.copy({w_name}, w_ub)"
    if spec.family == "layernorm" and len(spec.inputs) == 3:
        bias_name = spec.inputs[2].name
        bias_decl = (
            f"            b_ub = T.alloc_shared({w_shape}, {json.dumps(spec.inputs[2].dtype)})"
        )
        bias_load = f"            T.copy({bias_name}, b_ub)"
    var_calc = (
        "T.reducer_update(rsum[r], x[r, i])\n"
        "                        T.reducer_update(rsq[r], x[r, i] * x[r, i])"
        if is_layer
        else "T.reducer_update(rsq[r], x[r, i] * x[r, i])"
    )
    extra_reducer = (
        '                    rsum = T.alloc_reducer((ROWS,), T.float32, op="sum")\n'
        '                    T.reducer_init(rsum)\n'
        if is_layer
        else ""
    )
    extra_final = (
        "                    mu = T.alloc_fragment((ROWS,), T.float32)\n"
        "                    T.finalize_reducer(rsum, mu)\n"
        "                    for r in T.Parallel(ROWS):\n"
        "                        mu[r] = mu[r] / T.float32(D)\n"
        if is_layer
        else ""
    )
    inv_expr = (
        "T.rsqrt(T.max(var[r], T.float32(0)) + T.float32(EPS))"
        if is_layer
        else "T.rsqrt(sq[r] / T.float32(D) + T.float32(EPS))"
    )
    center = "(x[r, i] - mu[r])" if is_layer else "x[r, i]"
    out_expr = f"{center} * inv[r] * T.cast(w_ub[i], T.float32)"
    if is_layer and len(spec.inputs) == 3:
        out_expr += " + T.cast(b_ub[i], T.float32)"
    inputs_decl = ", ".join(_t(t.name, t) for t in spec.inputs)
    return _row_common(spec, plan) + f'''
    @T.prim_func
    def main({inputs_decl}, Y: T.Tensor({shape}, {json.dumps(dtype)})):
        with T.Kernel(CORES) as core:
{w_decl}
{bias_decl}
{w_load}
{bias_load}
            for t in T.Pipelined(ITERS, num_stages=2):
                base_row = (t * CORES + core) * ROWS
                with T.SimtVF(threads=THREADS):
                    x = T.alloc_fragment((ROWS, TILE), T.float32)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        row = T.min(base_row + r, BATCH - 1)
                        x[r, i] = T.if_then_else(i < D, T.cast(X[row, i], T.float32), T.float32(0))
{extra_reducer}                    rsq = T.alloc_reducer((ROWS,), T.float32, op="sum")
                    T.reducer_init(rsq)
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        {var_calc}
                    sq = T.alloc_fragment((ROWS,), T.float32)
                    T.finalize_reducer(rsq, sq)
{extra_final}                    var = T.alloc_fragment((ROWS,), T.float32)
                    for r in T.Parallel(ROWS):
                        var[r] = {"sq[r] / T.float32(D) - mu[r] * mu[r]" if is_layer else "sq[r]"}
                    inv = T.alloc_fragment((ROWS,), T.float32)
                    for r in T.Parallel(ROWS):
                        inv[r] = {inv_expr}
                    for r, i in T.Parallel(ROWS, TILE, coalesced_width=T.int32(1)):
                        if base_row + r < BATCH:
                            if i < D:
                                Y[base_row + r, i] = {"T.cast(" + out_expr + ", " + json.dumps(dtype) + ")" if dtype != "float32" else out_expr}

    return main
'''


def _gemm(spec: TaskSpec, plan: Plan) -> str:
    a, b = spec.inputs
    m, k = a.shape
    n = b.shape[0]
    dtype = a.dtype
    out_dtype = spec.output.dtype
    bm, bn, bk = plan.block_m, plan.block_n, plan.block_k
    nt = n // bn
    tiles = (m // bm) * nt
    epilogue = plan.epilogue
    c_alloc = ""
    store = ""
    if epilogue == "relu":
        c_alloc = f"            C_ub = T.alloc_shared(({bm // 2}, {bn}), T.float32)\n"
        store = f'''                T.dual_copy(C_l0c, C_ub)
                with T.SimtVF(threads=128):
                    for i, j in T.Parallel({bm // 2}, {bn}):
                        C_ub[i, j] = T.max(C_ub[i, j], T.float32(0))
                T.dual_copy(C_ub, C[m : m + BLOCK_M, n : n + BLOCK_N], l2_cache_ctrl="NOTALLOC_PW")
'''
    else:
        store = "                T.copy(C_l0c, C[m : m + BLOCK_M, n : n + BLOCK_N])\n"
    out_cast = ""
    if out_dtype != "float32":
        # Rare path: cast the L0C result through UB before storing.
        out_cast = ""
    return f'''def build():
    M, N, K = {m}, {n}, {k}
    BLOCK_M, BLOCK_N, BLOCK_K = {bm}, {bn}, {bk}
    BLOCKS = {plan.blocks}
    N_TILES = N // BLOCK_N
    TOTAL_TILES = (M // BLOCK_M) * N_TILES

    @T.prim_func
    def main(A: T.Tensor((M, K), {json.dumps(dtype)}), B: T.Tensor((N, K), {json.dumps(dtype)}), C: T.Tensor((M, N), {json.dumps(out_dtype)})):
        with T.Kernel(BLOCKS) as bx:
            A_l1 = T.alloc_l1((BLOCK_M, BLOCK_K), {json.dumps(dtype)})
            B_l1 = T.alloc_l1((BLOCK_N, BLOCK_K), {json.dumps(dtype)})
            C_l0c = T.alloc_l0c((BLOCK_M, BLOCK_N), T.float32)
{c_alloc}            for tile in T.Persistent([TOTAL_TILES], BLOCKS, bx):
                m = tile // N_TILES * BLOCK_M
                n = tile % N_TILES * BLOCK_N
                for kk in T.Pipelined(K // BLOCK_K, num_stages=2):
                    T.copy(A[m, kk * BLOCK_K], A_l1)
                    T.copy(B[n, kk * BLOCK_K], B_l1, l2_cache_ctrl="NOTALLOC_KEEP")
                    T.gemm(A_l1, B_l1, C_l0c, transpose_B=True, clear_accum=(kk == 0))
{store}
    return main
'''


TEMPLATE_NAME = {
    "elementwise_unary": "elementwise",
    "elementwise_binary": "elementwise",
    "row_reduce": "row_reduce",
    "softmax": "softmax",
    "rmsnorm": "rmsnorm",
    "layernorm": "layernorm",
    "gemm": "gemm",
}


def render(spec: TaskSpec, plan: Plan, pass_configs: dict[str, Any] | None = None) -> str:
    if spec.family in ("elementwise_unary", "elementwise_binary"):
        body = _elementwise(spec, plan)
    elif spec.family == "row_reduce":
        body = _row_reduce(spec, plan)
    elif spec.family == "softmax":
        body = _softmax(spec, plan)
    elif spec.family in ("rmsnorm", "layernorm"):
        body = _norm(spec, plan)
    elif spec.family == "gemm":
        body = _gemm(spec, plan)
    else:  # pragma: no cover
        raise ValueError(f"no template for {spec.family}")
    header = HEADER.format(
        name=spec.name,
        family=spec.family,
        plan_json=json.dumps(plan.to_dict(), sort_keys=True),
        template=TEMPLATE_NAME[spec.family],
        pass_configs=repr(pass_configs or {}),
    )
    return header + body


def write_kernel(spec: TaskSpec, plan: Plan, directory: str | Path, pass_configs: dict[str, Any] | None = None) -> Path:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{spec.name}.py"
    path.write_text(render(spec, plan, pass_configs), encoding="utf-8")
    return path
